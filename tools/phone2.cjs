const { chromium, devices } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const c = await b.newContext({ ...devices['Pixel 7'] })
  await c.addInitScript(() => { try { if (!localStorage.getItem('chernovik:profile:v1')) localStorage.setItem('chernovik:profile:v1', JSON.stringify({ stage: 'student', goals: ['job'] })) } catch {} })
  const p = await c.newPage()
  const errors = []; p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await p.goto('http://localhost:5173/#/train/onboarding'); await p.waitForTimeout(500)
  await p.getByRole('button', { name: /Начать/ }).click(); await p.waitForTimeout(600)
  for (let i = 0; i < 4; i++) {
    await p.locator('.composer__field').fill('Спрошу руководителя, какие задачи важнее, и предложу свой план на неделю')
    await p.locator('.composer__field').press('Enter')
    await p.waitForFunction(() => document.querySelector('.feedback__after'), null, { timeout: 60000 }); await p.waitForTimeout(700)
    if (i === 0) await p.screenshot({ path: 'out/ph2-review.png' })
    await p.getByRole('button', { name: /Следующий кейс|К итогам/ }).click(); await p.waitForTimeout(700)
  }
  await p.waitForSelector('.debrief__actions', { timeout: 60000 }); await p.waitForTimeout(3000)
  await p.evaluate(() => scrollTo(0, document.body.scrollHeight)); await p.waitForTimeout(500)
  await p.screenshot({ path: 'out/ph2-debrief.png' })
  await p.getByRole('button', { name: /Сохранить разбор/ }).click(); await p.waitForTimeout(1500)
  await p.screenshot({ path: 'out/ph2-report.png' })
  const d = await b.newContext({ viewport: { width: 1280, height: 820 } })
  await d.addInitScript(() => { try { localStorage.setItem('chernovik:profile:v1', '{}') } catch {} })
  const q = await d.newPage(); q.on('pageerror', (e) => errors.push(e.message))
  await q.goto('http://localhost:5173/'); await q.waitForTimeout(1200)
  await q.locator('.composer .nav-button').click(); await q.waitForTimeout(500)
  await q.screenshot({ path: 'out/d2-home.png' })
  console.log(errors.join('\n') || 'no errors')
  await b.close()
})()
