const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-audio-capture=${__dirname}/../audio/question.wav`] })
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, permissions: ['microphone'] })
  const page = await context.newPage()
  page.on('pageerror', (e) => console.log('page error:', e.message))
  const out = (n) => `demo/hi/${n}.png`
  await page.goto('http://localhost:5173/'); await page.waitForTimeout(1500)
  await page.mouse.move(300, 200)
  await page.getByRole('button', { name: 'Школа' }).click(); await page.waitForTimeout(250)
  await page.getByRole('button', { name: 'Поступление' }).click(); await page.waitForTimeout(250)
  await page.fill('.welcome__about', '11 класс, Ставрополь, люблю биологию')
  await page.waitForTimeout(500)
  await page.screenshot({ path: out('welcome') })
  await page.getByRole('button', { name: /Готово/ }).click(); await page.waitForTimeout(1600)
  await page.mouse.move(120, 120); await page.waitForTimeout(600)
  await page.screenshot({ path: out('home') })
  await page.getByRole('button', { name: 'Ответить голосом' }).click(); await page.waitForTimeout(2200)
  await page.screenshot({ path: out('voice') })
  await page.getByRole('button', { name: 'Отмена' }).click(); await page.waitForTimeout(500)
  await page.goto('http://localhost:5173/#/ask'); await page.waitForTimeout(600)
  await page.fill('textarea', 'хочу поступить в мпгу в ставрополе, что для этого нужно сделать?')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('.thinking')?.textContent.includes('Сверяю'), null, { timeout: 30000 })
  await page.screenshot({ path: out('web-status') })
  await page.waitForSelector('.exchange__after', { timeout: 90000 }); await page.waitForTimeout(1200)
  await page.evaluate(() => scrollTo(0, 0)); await page.waitForTimeout(300)
  await page.screenshot({ path: out('web-answer') })
  await page.locator('button.cite').first().click(); await page.waitForTimeout(1500)
  await page.screenshot({ path: out('web-proof') })
  await page.getByRole('button', { name: 'Сохранить в мою базу' }).click(); await page.waitForTimeout(500)
  await page.keyboard.press('Escape')
  await page.goto('http://localhost:5173/#/library'); await page.waitForTimeout(1200)
  await page.screenshot({ path: out('mybase') })
  await context.storageState({ path: 'demo/state-web.json' })
  await browser.close(); console.log('ok')
})()
