// Скриншоты в двойной плотности для README и презентации, с памятью из демо.
const { chromium } = require('playwright')
;(async () => {
  const [state, wav] = process.argv.slice(2)
  const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-audio-capture=${wav}%noloop`] })
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, storageState: state, permissions: ['microphone'] })
  await context.addInitScript(() => { if (!localStorage.getItem('chernovik:profile:v1')) localStorage.setItem('chernovik:profile:v1', JSON.stringify({ stage: 'student', goals: ['job'] })) })
  const page = await context.newPage()
  page.on('pageerror', (e) => console.log('page error:', e.message))
  const go = async (hash, wait = 1400) => { await page.goto('http://localhost:5173/#' + hash); await page.waitForTimeout(wait) }
  const out = (n) => `demo/hi/${n}.png`
  await go('/'); await page.screenshot({ path: out('home') })
  await go('/proofs'); await page.getByRole('button', { name: 'Проверить всю базу' }).click(); await page.waitForTimeout(900); await page.screenshot({ path: out('proofs') })
  await go('/library'); await page.evaluate(() => scrollTo(0, 420)); await page.waitForTimeout(300)
  await page.locator('.proof-badge').nth(1).click(); await page.waitForTimeout(1600); await page.screenshot({ path: out('sheet') })
  await go('/library'); await page.screenshot({ path: out('library') })
  await go('/progress'); await page.evaluate(() => scrollTo(0, 260)); await page.waitForTimeout(300); await page.screenshot({ path: out('progress') })
  await go('/ask'); await page.screenshot({ path: out('ask-empty') })
  await page.getByRole('button', { name: /слабые стороны/ }).click()
  await page.waitForSelector('.exchange__after', { timeout: 60000 }); await page.waitForTimeout(1500)
  await page.screenshot({ path: out('ask-answer') })
  await page.evaluate(() => scrollTo(0, document.querySelector('.sources').getBoundingClientRect().top + scrollY - 80)); await page.waitForTimeout(400)
  await page.screenshot({ path: out('ask-sources') })
  await go('/train/onboarding'); await page.screenshot({ path: out('intro') })
  await page.getByRole('button', { name: /Начать/ }).click(); await page.waitForTimeout(700); await page.screenshot({ path: out('case') })
  await page.getByRole('button', { name: 'Ответить голосом' }).click(); await page.waitForTimeout(4200); await page.screenshot({ path: out('voice') })
  await page.getByRole('button', { name: 'Отмена' }).click(); await page.waitForTimeout(400)
  await page.locator('.composer__field').fill('Скажу всё как есть и попрошу помощи, наверное')
  await page.locator('.composer__field').press('Enter')
  await page.waitForSelector('.feedback__after', { timeout: 60000 }); await page.waitForTimeout(1200)
  await page.evaluate(() => scrollTo(0, document.querySelector('.feedback').getBoundingClientRect().top + scrollY - 70)); await page.waitForTimeout(400)
  await page.screenshot({ path: out('review') })
  await page.evaluate(() => scrollTo(0, document.querySelector('.feedback__after').getBoundingClientRect().top + scrollY - 200)); await page.waitForTimeout(400)
  await page.screenshot({ path: out('review-after') })
  const id = await page.evaluate(() => JSON.parse(localStorage.getItem('chernovik:memory:v1')).sessions[0].id)
  await go('/report/' + id); await page.screenshot({ path: out('report') })
  await page.emulateMedia({ media: 'print' }); await page.pdf({ path: 'demo/hi/report.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true })
  await browser.close(); console.log('ok')
})()
