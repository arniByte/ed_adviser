const { chromium, devices } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const c = await b.newContext({ ...devices['Pixel 7'] })
  await c.addInitScript(() => { try { if (!localStorage.getItem('chernovik:profile:v1')) localStorage.setItem('chernovik:profile:v1', JSON.stringify({ stage: 'school', goals: ['admission'] })) } catch {} })
  const p = await c.newPage()
  const errors = []; p.on('pageerror', (e) => errors.push(e.message))
  const ask = async (q) => {
    const n = await p.locator('.exchange__after').count()
    await p.fill('textarea', q); await p.keyboard.press('Enter')
    await p.waitForFunction((n) => document.querySelectorAll('.exchange__after').length > n, n, { timeout: 90000 })
    await p.waitForTimeout(600)
    return p.evaluate(() => { const a = [...document.querySelectorAll('.exchange')].at(-1); return { text: a.querySelector('.rich')?.innerText.slice(0, 260), web: a.querySelector('.exchange__web')?.innerText, sources: [...a.querySelectorAll('.source__title')].map((e) => e.textContent.trim().slice(0, 60)) } })
  }
  await p.goto('http://localhost:5173/#/ask'); await p.waitForTimeout(600)
  console.log('1', await ask('Найди в интернете информацию как поступить в московские вузы?'))
  const mine = await p.evaluate(() => JSON.parse(localStorage.getItem('chernovik:mine:v1') || '[]').length)
  console.log('saved to my base:', mine)
  await p.reload(); await p.waitForTimeout(1200)
  console.log('after reload exchanges:', await p.locator('.exchange').count())
  await p.getByRole('button', { name: 'Новый разговор' }).click(); await p.waitForTimeout(400)
  console.log('2', await ask('Когда начинается приём документов в МГУ на бакалавриат?'))
  console.log(errors.join('\n') || 'no errors')
  await b.close()
})()
